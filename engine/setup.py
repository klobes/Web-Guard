def run(args, timeout=45):
    process = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    if process.returncode:
        raise RuntimeError(' '.join(args) + ': ' + (process.stderr or process.stdout).strip())
    return process.stdout


def write(path, data, mode=0o600):
    if isinstance(data, str):
        data = data.encode()
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.rm-webguard-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(data); handle.flush()
            os.fchmod(handle.fileno(), mode); os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def apache_module():
    source = (PACKAGE / 'RM_APACHE_SCAN_GUARD.sh').read_text()
    code = source.split("<<'RM_GUARD_PYTHON'\n", 1)[1].rsplit('\nRM_GUARD_PYTHON', 1)[0]
    code = code.split('\nparser = argparse.ArgumentParser', 1)[0]
    module = {}
    exec(compile(code, str(PACKAGE / 'RM_APACHE_SCAN_GUARD.sh'), 'exec'), module)
    module['GUARD_TEXT'] += (
        '\n# Restore IP only from the local Cloudflare Tunnel connector.\n'
        'RemoteIPHeader CF-Connecting-IP\n'
        'RemoteIPTrustedProxy 127.0.0.1\n'
        'RemoteIPTrustedProxy ::1\n'
        '# Do not log query strings, cookies or Authorization headers.\n'
        'LogFormat "%a - - %t \\"%m %U %H\\" %>s" rm_webguard\n'
        'CustomLog /var/log/rm-webguard/access.log rm_webguard\n'
    ).encode()
    return module


def render_jails(settings):
    output = GENERATED
    for name in JAILS:
        jail = settings['jails'][name]
        enabled = settings['enabled'] and jail['enabled']
        output += '\n[' + name + ']\n'
        action = 'rm-webguard-cf[name=' + name + ']'
        if settings['local_firewall'] and not settings['dry_run']:
            action = ('iptables-multiport[name=' + name + ',port=5555,protocol=tcp]\n'
                      '         ' + action)
        fields = {'enabled': str(enabled).lower(), 'filter': name, 'backend':'polling',
                  'usedns':'no', 'logpath':str(LOG) + ' tail',
                  'ignoreip':' '.join(settings['ignoreip']), 'ignoreself':'true',
                  'maxretry':str(jail['maxretry']), 'findtime':str(jail['findtime']),
                  'bantime':str(jail['bantime']),
                  'bantime.increment':str(settings['increment_bantime']).lower(),
                  'bantime.maxtime':str(settings['maximum_bantime_seconds']),
                  'action':action}
        output += ''.join(key + ' = ' + value + '\n' for key,value in fields.items())
    return output


def detector_unban(ip=None, ignore_settings=None):
    for jail in JAILS:
        try:
            # A disabled jail has no runtime object. Query it before set/unbanip.
            addresses = run(['fail2ban-client','get',jail,'banip']).split()
        except RuntimeError:
            continue
        for address in addresses:
            try:
                address = str(canonical_ip(address))
                if ip is not None and address != ip:
                    continue
                if ignore_settings is not None and not ignored(canonical_ip(address),ignore_settings):
                    continue
                run(['fail2ban-client','set',jail,'unbanip',address], timeout=150)
            except ValueError:
                continue


FILTER_DIR = Path('/etc/fail2ban/filter.d')
# Real URLs of the site: a custom path list must never match any of these.
LEGIT_URIS = ('/', '/admin', '/admin/login', '/login', '/api/v1/items', '/storage/brands/home.png',
              '/vendor/core/plugins/web-guard/css/webguard.css', '/favicon.ico', '/robots.txt',
              '/admin/radius-manager/system/realtime', '/products/example', '/cdn-cgi/styles/cf.errors.css')


def render_filters(settings):
    """Installed base filter plus the panel's custom paths, per path-based jail."""
    paths = settings.get('paths') or {}
    return {name: '# RM WebGuard v1\n' + render_filter((OPT / 'filters' / (name + '.conf')).read_text(), paths.get(name, []))
            for name in PATH_JAILS}


def test_custom_filters(settings, filters):
    """Prove each candidate filter matches its own paths and none of the legitimate URLs."""
    stamp = datetime.datetime.now().astimezone().strftime('%d/%b/%Y:%H:%M:%S %z')
    for name in PATH_JAILS:
        items = (settings.get('paths') or {}).get(name, [])
        if not items:
            continue
        positives = ['/' + item['value'] if item['type'] == 'segment' else '/wg-test.' + item['value']
                     for item in items]
        with tempfile.TemporaryDirectory(prefix='rm-webguard-paths-test-') as directory:
            log = Path(directory) / 'requests.log'
            candidate = Path(directory) / (name + '.conf')
            log.write_text(''.join('198.51.100.23 - - [' + stamp + '] "GET ' + uri + ' HTTP/1.1" 404\n'
                                   for uri in positives + list(LEGIT_URIS)))
            candidate.write_text(filters[name])
            output = run(['fail2ban-regex', str(log), str(candidate)], timeout=90)
        summary = re.search(r'Lines:.*?\b([0-9]+) matched', output)
        if not summary or int(summary.group(1)) != len(positives):
            raise RuntimeError('Testi i rrugeve te ' + name + ' deshtoi: duhej te kapte ' + str(len(positives))
                               + ' rruge dhe asnje URL te ligjshme. ' + output[-900:])


def vhost_block(newline='\n'):
    return newline.join(('    ' + LOCK_BEGIN,
                         '    IncludeOptional "' + str(CUSTOMFILE) + '"',
                         '    IncludeOptional "' + str(LOCKFILE) + '"',
                         '    ' + LOCK_END, ''))


def include_installed(path):
    try:
        text = SITE.read_text()
    except OSError:
        return False
    return LOCK_BEGIN in text and str(path) in text


def site_host():
    try:
        value = json.loads((CONFIG / 'panel-bridge.json').read_text()).get('host', '')
    except (OSError, ValueError):
        value = ''
    return value if re.fullmatch(r'[A-Za-z0-9.-]{3,253}', value or '') else 'klobes.al'


def lockdown_install():
    """Idempotent: include the managed Apache files inside VirtualHost *:5555 (own markers, backup, rollback), then sync."""
    if os.geteuid() != 0:
        raise RuntimeError('Ekzekutoje me sudo')
    site = SITE.resolve(strict=True)
    original = site.read_bytes()
    text = original.decode('utf-8')
    if text.count(LOCK_BEGIN) > 1 or text.count(LOCK_END) != text.count(LOCK_BEGIN):
        raise RuntimeError('Blloku i lockdown eshte i dyfishuar ose i ndryshuar; kontrollo vhost-in.')
    newline = '\r\n' if '\r\n' in text else '\n'
    block = vhost_block(newline)
    existing = re.search(r'^[ \t]*' + re.escape(LOCK_BEGIN) + r'.*?' + re.escape(LOCK_END) + r'[ \t]*\r?\n', text, re.S | re.M)
    if existing:
        modified = text[:existing.start()] + block + text[existing.end():]
    else:
        if text.count(GUARD_END) != 1:
            raise RuntimeError('Nuk u gjet blloku i scan guard te :5555; instalo fillimisht guard-in.')
        position = text.index('\n', text.index(GUARD_END)) + 1
        modified = text[:position] + block + text[position:]
    if modified != text:
        backup = Path('/var/backups/rm-webguard-lockdown')
        backup.mkdir(parents=True, exist_ok=True, mode=0o700)
        shutil.copy2(site, backup / (datetime.datetime.now().strftime('%Y%m%d_%H%M%S') + '.vhost.before'))
        try:
            LOCKFILE.parent.mkdir(parents=True, exist_ok=True)
            write(site, modified.encode(), 0o644)
            run(['apache2ctl', 'configtest'])
            run(['systemctl', 'reload', 'apache2'], timeout=90)
        except Exception:
            write(site, original, 0o644)
            try:
                run(['systemctl', 'reload', 'apache2'], timeout=90)
            except Exception:
                print('ERROR: kontrollo Apache pas kthimit.', file=sys.stderr)
            raise
        print('APACHE_INCLUDE=INSTALLED', flush=True)
    if LEGACY_LOCKFILE.exists() and LEGACY_LOCKFILE.read_bytes().startswith(LOCKDOWN_MARK.encode()):
        LEGACY_LOCKFILE.unlink()
        run(['systemctl', 'reload', 'apache2'], timeout=90)
    if (CONFIG / 'active.json').exists():
        lockdown_sync()
        custom_sync()


def put_managed(path, data, mark, label):
    """Write (bytes) or remove (None) a managed Apache file, prove the config, reload; restore on failure."""
    if data is not None and not include_installed(path):
        raise RuntimeError(label + ' nuk eshte lidhur me Apache. Ekzekuto: sudo rm-webguard lockdown-install')
    current = path.read_bytes() if path.exists() else None
    if current is not None and not current.startswith(mark.encode()):
        raise RuntimeError(str(path) + ' nuk eshte skedar i menaxhuar; nuk mbishkruhet')
    if current == data:
        return False
    try:
        if data is None:
            path.unlink()
        else:
            write(path, data, 0o644)
        run(['apache2ctl', 'configtest'])
        run(['systemctl', 'reload', 'apache2'], timeout=90)
    except Exception:
        if current is None:
            path.unlink(missing_ok=True)
        else:
            write(path, current, 0o644)
        try:
            run(['systemctl', 'reload', 'apache2'], timeout=90)
        except Exception:
            print('ERROR: kontrollo Apache pas kthimit te ' + path.name + '.', file=sys.stderr)
        raise
    return True


def put_lockdown(data):
    return put_managed(LOCKFILE, data, LOCKDOWN_MARK, 'Lockdown')


def put_custom(data):
    return put_managed(CUSTOMFILE, data, CUSTOM_MARK, 'Rregullat e rrugeve')


def http_status(path):
    return run(['curl', '--noproxy', '*', '-sS', '--max-time', '15', '-o', '/dev/null', '-H', 'Host: ' + site_host(),
                '-w', '%{http_code}', 'http://127.0.0.1:5555' + path], timeout=20).strip()


def verify_custom(settings):
    """Live proof after the reload: the home page is not refused and the panel's own paths are."""
    if http_status('/') == '403':
        raise RuntimeError('Rregullat e rrugeve refuzojne faqen kryesore; u rikthyen.')
    items = [item for jail in PATH_JAILS for item in (settings.get('paths') or {}).get(jail, [])]
    sample = '/' + items[0]['value'] if items[0]['type'] == 'segment' else '/wg-test.' + items[0]['value']
    if http_status(sample) != '403':
        raise RuntimeError('Apache nuk e refuzoi rrugen e provës ' + sample + '; u rikthyen.')


def apply_custom(settings):
    previous = CUSTOMFILE.read_bytes() if CUSTOMFILE.exists() else None
    text = render_custom_guard(settings)
    changed = put_custom(None if text is None else text.encode())
    if changed and text:
        try:
            verify_custom(settings)
        except Exception:
            put_custom(previous)
            raise
    if changed:
        print('APACHE_PATHS=' + ('ON' if text else 'OFF'), flush=True)
    return changed


def custom_sync():
    apply_custom(validate(json.loads((CONFIG / 'active.json').read_text())))


def apply_lockdown(settings):
    text = render_lockdown(settings)
    changed = put_lockdown(None if text is None else text.encode())
    if changed:
        print('LOCKDOWN=' + ('ON' if text else 'OFF'), flush=True)
    return changed


def lockdown_sync():
    """Idempotent: make Apache match active.json (removes an expired lockdown)."""
    apply_lockdown(validate(json.loads((CONFIG / 'active.json').read_text())))


def lockdown_off():
    """Emergency exit: needs no Fail2ban or Cloudflare checks."""
    for name in ('settings.json', 'active.json'):
        path = CONFIG / name
        if path.exists():
            data = json.loads(path.read_text())
            if 'lockdown' in data:
                data['lockdown'] = {'level': 'off', 'until': 0}
                write(path, json.dumps(data, indent=2) + '\n')
    put_lockdown(None)
    print('LOCKDOWN=OFF')


def apply_settings():
    settings = validate(json.loads((CONFIG / 'settings.json').read_text()))
    previous_active = (CONFIG / 'active.json').read_bytes() if (CONFIG / 'active.json').exists() else None
    previous_jail = JAILFILE.read_bytes() if JAILFILE.exists() else None
    if previous_jail is not None and not previous_jail.startswith(GENERATED.encode()):
        raise RuntimeError('rm-webguard.local nuk eshte skedar i menaxhuar; nuk mbishkruhet')
    previous_settings = json.loads(previous_active) if previous_active else None
    if previous_settings and previous_settings['instance_id'] != settings['instance_id']:
        raise RuntimeError('instance_id eshte identiteti i modulit dhe nuk duhet ndryshuar')
    if previous_settings and previous_settings['zone_id'] != settings['zone_id']:
        database = STATE / 'state.sqlite3'
        if database.exists():
            with sqlite3.connect('file:'+str(database)+'?mode=ro',uri=True) as connection:
                owned = connection.execute('SELECT 1 FROM leases UNION SELECT 1 FROM edge WHERE status<>"released" LIMIT 1').fetchone()
                touched = connection.execute('SELECT value FROM meta WHERE key="remote_touched"').fetchone()
                if owned or (touched and touched[0]=='1'):
                    raise RuntimeError('Zhblloko IP-te e modulit para ndryshimit te zone_id')
    if settings['enabled'] and not settings['dry_run'] and settings['local_firewall']:
        if not shutil.which('iptables'):
            raise RuntimeError('iptables mungon; instaloje ose vendos local_firewall=false')
        run(['iptables','-S'])
    # Build and prove the custom-path filters before anything is changed.
    filters = render_filters(settings)
    test_custom_filters(settings, filters)
    previous_lock = LOCKFILE.read_bytes() if LOCKFILE.exists() else None
    previous_custom = CUSTOMFILE.read_bytes() if CUSTOMFILE.exists() else None
    previous_filters = {name: (FILTER_DIR / (name + '.conf')).read_bytes() if (FILTER_DIR / (name + '.conf')).exists() else None
                        for name in PATH_JAILS}
    # Drop monitor-only tickets before changing to enforcement, while the old
    # action configuration is still active; do not restore hypothetical bans.
    if previous_settings and previous_settings['dry_run'] and not settings['dry_run']:
        detector_unban()
    try:
        write(CONFIG / 'active.json', json.dumps(settings,indent=2) + '\n')
        if settings['enabled'] and not settings['dry_run']:
            run(['/usr/bin/python3', str(OPT / 'cf_action.py'), 'api-check', 'write'], timeout=90)
        detector_unban(ignore_settings=settings)
        apply_lockdown(settings)
        apply_custom(settings)
        for name, text in filters.items():
            path = FILTER_DIR / (name + '.conf')
            if not path.exists() or path.read_text() != text:
                write(path, text, 0o644)
        write(JAILFILE, render_jails(settings))
        run(['fail2ban-client', '-t'])
        run(['fail2ban-client', 'reload'], timeout=150)
    except Exception:
        if previous_active is None:
            (CONFIG / 'active.json').unlink(missing_ok=True)
        else:
            write(CONFIG / 'active.json', previous_active)
        if previous_jail is None:
            JAILFILE.unlink(missing_ok=True)
        else:
            write(JAILFILE, previous_jail)
        try:
            put_lockdown(previous_lock)
        except Exception:
            print('ERROR: lockdown nuk u rikthye; ekzekuto: sudo rm-webguard lockdown-off', file=sys.stderr)
        try:
            put_custom(previous_custom)
        except Exception:
            print('ERROR: rregullat e rrugeve te Apache nuk u rikthyen; ekzekuto: sudo rm-webguard paths-sync', file=sys.stderr)
        for name, data in previous_filters.items():
            path = FILTER_DIR / (name + '.conf')
            if data is None:
                path.unlink(missing_ok=True)
            else:
                write(path, data, 0o644)
        try:
            run(['fail2ban-client', 'reload'], timeout=150)
        except Exception:
            print('ERROR: kontrollo Fail2ban pas kthimit te konfigurimit.', file=sys.stderr)
        raise
    print('SETTINGS=PASS MODE=' + ('DISABLED' if not settings['enabled'] else 'MONITOR' if settings['dry_run'] else 'ENFORCE'), flush=True)


def prerequisites():
    if os.geteuid() != 0:
        raise RuntimeError('Ekzekutoje me sudo')
    for command in ('apache2ctl','a2enmod','systemctl','curl','fail2ban-client','fail2ban-regex'):
        if not shutil.which(command):
            raise RuntimeError(command + ' mungon. Per Fail2ban: sudo apt install fail2ban')
    run(['apache2ctl','configtest'])
    run(['systemctl','is-active','--quiet','apache2'])
    run(['fail2ban-client','ping'])
    version = __import__('re').search(r'([0-9]+)\.([0-9]+)',run(['fail2ban-client','-V']))
    if not version or tuple(map(int,version.groups())) < (0,11):
        raise RuntimeError('Kerkohet Fail2ban >= 0.11')


def test_filters():
    stamp = datetime.datetime.now().astimezone().strftime('%d/%b/%Y:%H:%M:%S %z')
    rows = [
        ('198.51.100.23','GET','/wp/wp-includes/js/wp-emoji.js',404),
        ('2001:db8::23','POST','/blog/wp-admin/admin-ajax.php',403),
        ('198.51.100.23','GET','/.env',403),
        ('198.51.100.23','GET','/.git/config',403),
        ('198.51.100.23','GET','/old/wp-config.php',404),
        ('198.51.100.23','GET','/',200),
        ('198.51.100.23','GET','/favicon.ico',404),
        ('198.51.100.23','GET','/admin/radius-manager/system/realtime',200),
    ]
    with tempfile.TemporaryDirectory(prefix='rm-webguard-filter-test-') as directory:
        path = Path(directory)/'requests.log'
        path.write_text(''.join(ip+' - - ['+stamp+'] "'+method+' '+uri+' HTTP/1.1" '+str(status)+'\n'
                                for ip,method,uri,status in rows))
        for name, expected in zip(JAILS,(2,3,1)):
            output = run(['fail2ban-regex',str(path),str(Path('/etc/fail2ban/filter.d')/(name+'.conf'))])
            summary = __import__('re').search(r'Lines:.*?\b([0-9]+) matched',output)
            if not summary or int(summary.group(1)) != expected:
                raise RuntimeError('Testi i filtrit '+name+' deshtoi: '+output[-1800:])
    print('LIVE_FILTER_TESTS=PASS (8 positive/negative fixture requests)',flush=True)


def install():
    prerequisites()
    if OPT.exists() and not (OPT / '.rm-webguard-owned').exists():
        raise RuntimeError('/opt/rm-webguard ekziston dhe nuk eshte i ketij moduli')
    for name in JAILS:
        destination = Path('/etc/fail2ban/filter.d') / (name + '.conf')
        if destination.exists() and not destination.read_text().startswith('# RM WebGuard v1\n'):
            raise RuntimeError(str(destination) + ' ekziston pa shenje pronësie')
    action_path = Path('/etc/fail2ban/action.d/rm-webguard-cf.conf')
    if action_path.exists() and not action_path.read_text().startswith('# RM WebGuard v1\n'):
        raise RuntimeError(str(action_path) + ' ekziston pa shenje pronësie')
    CONFIG.mkdir(parents=True, exist_ok=True, mode=0o700)
    STATE.mkdir(parents=True, exist_ok=True, mode=0o700)
    OPT.mkdir(parents=True, exist_ok=True, mode=0o755)
    for name in ('common.py','cf_action.py','telemetry.py','setup.py','RM_APACHE_SCAN_GUARD.sh','settings.json',
                 'rm-webguard-cf.conf','rm-webguard-reconcile.service','rm-webguard-reconcile.timer'):
        write(OPT / name, (PACKAGE / name).read_bytes(), 0o644)
    for name in JAILS:
        write(OPT / 'filters' / (name+'.conf'), (PACKAGE/'filters'/(name+'.conf')).read_bytes(), 0o644)
    write(OPT / '.rm-webguard-owned', 'RM WebGuard v1\n')
    if not (CONFIG / 'settings.json').exists():
        settings = json.loads((PACKAGE / 'settings.json').read_text())
        settings['instance_id'] = uuid.uuid4().hex
        write(CONFIG / 'settings.json', json.dumps(settings,indent=2) + '\n')
    validate(json.loads((CONFIG / 'settings.json').read_text()))
    for name in JAILS:
        write(Path('/etc/fail2ban/filter.d') / (name + '.conf'),
              '# RM WebGuard v1\n' + (PACKAGE / 'filters' / (name + '.conf')).read_text(), 0o644)
    write(action_path, '# RM WebGuard v1\n' + (PACKAGE / 'rm-webguard-cf.conf').read_text(), 0o644)
    test_filters()
    LOG.parent.mkdir(parents=True,exist_ok=True,mode=0o750)
    # Load the module; its trusted-proxy directives are scoped to :5555.
    run(['a2enmod','remoteip'])
    guard = apache_module()
    was_installed = guard['BEGIN'].encode() in guard['SITE'].resolve().read_bytes()
    try:
        guard['main']('install')
        # Prove that the request IP is restored in the dedicated log. The
        # documentation address is ignored by the action and cannot ban a user.
        test_ip = '198.51.100.23'
        run(['curl','--noproxy','*','-sS','--max-time','15','-o','/dev/null',
             '-H','Host: klobes.al','-H','CF-Connecting-IP: '+test_ip,
             'http://127.0.0.1:5555/'], timeout=20)
        if not LOG.exists():
            raise RuntimeError('Log-u i vecante nuk u krijua')
        with LOG.open(errors='replace') as handle:
            lines = collections.deque(handle,maxlen=10)
        if not any(line.startswith(test_ip+' - - ') for line in lines):
            raise RuntimeError('IP real nuk u verifikua ne log-un e vecante')
        LOG.chmod(0o640)
        apply_settings()
    except Exception:
        if not was_installed:
            guard['main']('remove')
        raise
    write(LOCAL, '#!/usr/bin/env bash\nexec /usr/bin/python3 /opt/rm-webguard/setup.py "$@"\n', 0o755)
    for name in ('rm-webguard-reconcile.service','rm-webguard-reconcile.timer'):
        write(Path('/etc/systemd/system') / name, (PACKAGE / name).read_bytes(), 0o644)
    write(Path('/etc/logrotate.d/rm-webguard'),
          str(LOG) + ' {\n    daily\n    rotate 14\n    missingok\n    notifempty\n    compress\n    delaycompress\n    create 640 root adm\n    sharedscripts\n    postrotate\n        /usr/sbin/apache2ctl graceful > /dev/null 2>&1 || true\n    endscript\n}\n', 0o644)
    run(['systemctl','daemon-reload'])
    run(['systemctl','enable','--now','rm-webguard-reconcile.timer'])
    print('INSTALL=PASS SETTINGS=/etc/rm-webguard/settings.json', flush=True)


def main():
    parser = argparse.ArgumentParser(description='RM WebGuard: zbulim skanimi dhe bllokime IP me afat.')
    parser.add_argument('action', choices=('install','apply','status','token','unban','api-check','disable','remove','lockdown-off','lockdown-sync','lockdown-install','paths-sync'))
    parser.add_argument('ip', nargs='?')
    arguments = parser.parse_args()
    if os.geteuid() != 0:
        raise RuntimeError('Ekzekutoje me sudo')
    action = arguments.action
    if action == 'install':
        install()
    elif action == 'apply':
        prerequisites(); apply_settings()
    elif action == 'lockdown-off':
        lockdown_off()
    elif action == 'lockdown-install':
        lockdown_install()
    elif action == 'paths-sync':
        custom_sync()
    elif action == 'lockdown-sync':
        lockdown_sync()
    elif action == 'token':
        token = getpass.getpass('Cloudflare API Token (nuk shfaqet): ').strip()
        if not token or any(character.isspace() for character in token):
            raise RuntimeError('Token bosh ose i pavlefshem')
        write(CONFIG / 'cloudflare.token', token + '\n')
        print('TOKEN=STORED (root, 600)')
    elif action in ('status','api-check'):
        command = ['/usr/bin/python3',str(OPT/'cf_action.py'),action]
        if action == 'api-check':
            command.append('write')
        print(run(command,timeout=90))
        if action == 'status':
            for jail in JAILS:
                try:
                    print(run(['fail2ban-client','status',jail]))
                except RuntimeError:
                    print(jail + ': jo aktiv')
    elif action == 'unban':
        if not arguments.ip:
            raise RuntimeError('Perdor: rm-webguard unban IP')
        address = str(canonical_ip(arguments.ip))
        detector_unban(address)
        print(run(['/usr/bin/python3',str(OPT/'cf_action.py'),'unban',address],timeout=150))
    elif action in ('disable','remove'):
        settings = json.loads((CONFIG/'settings.json').read_text())
        settings['enabled'] = False
        write(CONFIG/'settings.json',json.dumps(settings,indent=2)+'\n')
        apply_settings()
        print(run(['/usr/bin/python3',str(OPT/'cf_action.py'),'release-all'],timeout=150))
        # Do not stop the cleanup timer while owned remote blocks remain.
        from cf_action import Cloudflare
        if settings['zone_id'] and (CONFIG/'cloudflare.token').exists():
            if Cloudflare(validate(settings)).owned_rules():
                raise RuntimeError('Ka zhbllokime ne pritje; timer vazhdon. Perserit remove pasi te pastrohen.')
        if action == 'remove':
            lockdown_off()
            put_custom(None)
            run(['systemctl','disable','--now','rm-webguard-reconcile.timer'])
            apache_module()['main']('remove')
            JAILFILE.unlink(missing_ok=True)
            print('REMOVE=PASS; kodi, settings dhe historiku ruhen per kontroll/rikthim.')
    else:
        parser.error('Veprim i panjohur')


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print('ERROR: '+str(error),file=sys.stderr)
